//! Built-in pixel fonts, drawn for this project as text bitmaps.
//!
//! Each glyph is `(char, top, rows)`: `rows` use `#` for ink and `.` for empty, `top` is the
//! first row in *body* coordinates (row 0 = top of the capitals, the baseline is right below
//! the last capital row, descenders go under it). Every font reserves an accent zone above the
//! body, so accented capitals fit inside the line box. Accented letters are composed from a base
//! letter plus an accent mark (see [`super::font`]).

/// Accent marks used to compose accented letters.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Accent {
    Acute,
    Grave,
    Circumflex,
    Tilde,
    Diaeresis,
    Cedilla,
}

/// Raw description of one built-in font.
pub(crate) struct FontData {
    pub name: &'static str,
    /// Rows reserved above the capitals for accents.
    pub zone: u32,
    /// Capital height (rows from the cap top to the baseline).
    pub cap_height: u32,
    /// Rows below the baseline.
    pub descent: u32,
    pub line_height: u32,
    pub letter_spacing: i32,
    pub space_width: u32,
    pub glyphs: &'static [(char, u32, &'static [&'static str])],
    /// Accent bitmaps: (accent, for odd-width bases, for even-width bases). Two rows each.
    pub accents: &'static [(Accent, [&'static str; 2], [&'static str; 2])],
    /// Drawn for characters the font lacks.
    pub replacement: &'static [&'static str],
}

